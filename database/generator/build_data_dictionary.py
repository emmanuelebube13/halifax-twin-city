"""Generate the data dictionary (step 11) from the logical model and the physical SQL.

Reads, never writes, these inputs:
- database/generator/logical_model_spec.py   entities, attributes, domains, notes
- database/sql/02_silver_tables.sql          physical columns, types, nullability, keys, checks
- database/sql/03_foreign_keys_and_indexes.sql  foreign keys
- database/sql/04_scd2_history.sql           which tables keep SCD Type 2 history
- database/sql/06_bronze_register.sql        bronze.feed_fetch
- database/sql/07_comments.sql               the description of every table and column

Writes:
- engineering/model/data-dictionary.csv
- engineering/model/data-dictionary.md

The output depends only on the inputs (no dates, no machine names), so a re-run
reproduces both files byte for byte. `--check` compares instead of writing and
exits 1 if either file would change.

Usage (from the repository root):
    python database/generator/build_data_dictionary.py
    python database/generator/build_data_dictionary.py --check
"""
from __future__ import annotations

import argparse
import csv
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SQL = os.path.join(REPO, "database", "sql")
OUT_DIR = os.path.join(REPO, "engineering", "model")

AREA_ORDER = ["Core", "Transportation", "Public Works", "Housing & Real Estate"]
WEEKDAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]

CSV_COLUMNS = [
    "schema_name", "table_name", "entity_name", "subject_area", "entity_kind", "supertype",
    "history", "column_position", "column_name", "attribute_name", "column_class",
    "domain", "data_type", "nullable", "default_or_generated", "logical_key",
    "physical_keys", "references", "check_rule", "description",
]


# ---------------------------------------------------------------- inputs
def load_spec() -> dict:
    """Execute the spec in its own namespace and return its entity dict E."""
    ns: dict = {}
    path = os.path.join(HERE, "logical_model_spec.py")
    with open(path, encoding="utf-8") as fh:
        exec(compile(fh.read(), path, "exec"), ns)
    return ns["E"]


def pname(s: str) -> str:
    """Physical name of a logical name. Same rule as build_physical_sql.py."""
    s = s.replace("'", "")
    s = re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").lower()
    s = re.sub(r"(^|_)timestamp($|_)", r"\1ts\2", s)
    return s


def read(name: str) -> str:
    with open(os.path.join(SQL, name), encoding="utf-8") as fh:
        return fh.read()


TYPE_RE = re.compile(r"^(geometry\([^)]*\)|numeric\(\d+,\d+\)|varchar\(\d+\)|char\(\d+\)|[a-z]+)")


def parse_column_line(line: str) -> dict:
    """Parse one column definition from a CREATE TABLE body."""
    line = line.strip().rstrip(",")
    name, rest = line.split(None, 1)
    m = TYPE_RE.match(rest)
    typ = m.group(1)
    tail = rest[m.end():]
    default = ""
    if "GENERATED BY DEFAULT AS IDENTITY" in tail:
        default = "identity (by default)"
    elif "GENERATED ALWAYS AS IDENTITY" in tail:
        default = "identity (always)"
    elif "GENERATED ALWAYS AS (" in tail:
        expr = tail.split("GENERATED ALWAYS AS ", 1)[1].rsplit(" STORED", 1)[0]
        default = "generated: " + expr.strip()[1:-1]
    else:
        dm = re.search(r"DEFAULT (\S+)", tail)
        if dm:
            default = "default " + dm.group(1)
    nullable = "No" if ("NOT NULL" in tail or "PRIMARY KEY" in tail) else "Yes"
    inline = {}
    if "PRIMARY KEY" in tail:
        inline["pk"] = True
    rm = re.search(r"REFERENCES (\w+)\.(\w+) \((\w+)\)", tail)
    if rm:
        inline["ref"] = f"{rm.group(1)}.{rm.group(2)}.{rm.group(3)}"
    cm = re.search(r"CHECK \((.*)\)", tail)
    if cm:
        inline["check"] = cm.group(1)
    return dict(name=name, type=typ, nullable=nullable, default=default, inline=inline)


def parse_tables(text: str, schema: str) -> dict:
    """Return {table: dict(cols=[...], pk=[...], aks={name: [cols]}, checks={col: [expr]})}."""
    tables: dict = {}
    pattern = re.compile(rf"^CREATE TABLE {schema}\.(\w+) \(\n(.*?)\n\)", re.S | re.M)
    for m in pattern.finditer(text):
        t = m.group(1)
        info = dict(cols=[], pk=[], aks={}, checks={})
        for raw in m.group(2).split("\n"):
            line = raw.strip().rstrip(",")
            if not line:
                continue
            if line.startswith("CONSTRAINT "):
                parts = line.split(None, 2)
                cname, body = parts[1], parts[2]
                if body.startswith("PRIMARY KEY"):
                    info["pk"] = [c.strip() for c in body[body.index("(") + 1:body.rindex(")")].split(",")]
                elif body.startswith("UNIQUE"):
                    info["aks"][cname] = [c.strip() for c in body[body.index("(") + 1:body.rindex(")")].split(",")]
                elif body.startswith("CHECK"):
                    expr = body[body.index("(") + 1:body.rindex(")")]
                    col = expr.split()[0]
                    info["checks"].setdefault(col, []).append(expr)
                continue
            col = parse_column_line(line)
            if col["inline"].get("pk"):
                info["pk"] = [col["name"]]
            if "check" in col["inline"]:
                info["checks"].setdefault(col["name"], []).append(col["inline"]["check"])
            info["cols"].append(col)
        tables[t] = info
    return tables


def parse_fks(text: str) -> dict:
    """Return {(table, column): 'silver.parent.column'} for single and composite keys."""
    fks: dict = {}
    pattern = re.compile(
        r"ALTER TABLE silver\.(\w+) ADD CONSTRAINT (\w+)\n\s+FOREIGN KEY \(([^)]*)\) REFERENCES silver\.(\w+) \(([^)]*)\);")
    for m in pattern.finditer(text):
        child, _name, ccols, parent, pcols = m.groups()
        cc = [c.strip() for c in ccols.split(",")]
        pc = [c.strip() for c in pcols.split(",")]
        for c, p in zip(cc, pc):
            fks.setdefault((child, c), []).append(f"silver.{parent}.{p}")
    return fks


def parse_scd2(text: str) -> set:
    return set(re.findall(r"CREATE TRIGGER trg_(\w+)_scd2 ", text))


COMMENT_RE = re.compile(r"^COMMENT ON (TABLE|COLUMN) (\w+)\.([\w.]+) IS '((?:[^']|'')*)';$", re.M)


def parse_comments(*texts: str) -> tuple[dict, dict]:
    tables, columns = {}, {}
    for text in texts:
        for kind, schema, obj, body in COMMENT_RE.findall(text):
            body = body.replace("''", "'")
            if kind == "TABLE":
                tables[f"{schema}.{obj}"] = body
            else:
                columns[f"{schema}.{obj}"] = body
    return tables, columns


# ---------------------------------------------------------------- build
def logical_attrs(E: dict, entity: str) -> dict:
    """{physical column: (attribute name, key, domain, null, note)} for one entity."""
    out = {}
    for a in E[entity]["attrs"]:
        if a[0] == "Monday Flag":
            for d in WEEKDAYS:
                out[pname(f"{d} Flag")] = (f"{d} Flag", a[1], a[2], a[3], a[4] if d == "Monday" else "")
        else:
            out[pname(a[0])] = a
    return out


def column_class(col: str, attr) -> str:
    if col in ("dw_loaded_ts", "dw_batch_id"):
        return "Audit"
    if col == "valid_from_ts":
        return "SCD2"
    if attr is None:
        return "Derived"
    return "Logical"


def build_rows() -> list[dict]:
    E = load_spec()
    s02 = read("02_silver_tables.sql")
    s03 = read("03_foreign_keys_and_indexes.sql")
    s04 = read("04_scd2_history.sql")
    s06 = read("06_bronze_register.sql")
    s07 = read("07_comments.sql")

    silver = parse_tables(s02, "silver")
    bronze = parse_tables(s06, "bronze")
    fks = parse_fks(s03)
    scd2 = parse_scd2(s04)
    tcom, ccom = parse_comments(s07, s06)

    by_table = {pname(n): n for n in E}
    missing = sorted(set(silver) - set(by_table))
    if missing:
        raise SystemExit(f"Tables in 02_silver_tables.sql with no entity in the spec: {missing}")
    extra = sorted(set(by_table) - set(silver))
    if extra:
        raise SystemExit(f"Entities in the spec with no table in 02_silver_tables.sql: {extra}")

    # Event attributes, for the rolled-down vehicle_position columns.
    event_attrs = logical_attrs(E, "Event")
    rows = []
    for area in AREA_ORDER:
        for t, info in silver.items():
            entity = by_table[t]
            spec = E[entity]
            if spec["area"] != area:
                continue
            attrs = logical_attrs(E, entity)
            kind = "Rolled-down event" if t == "vehicle_position" else spec["kind"]
            history = "SCD Type 2" if t in scd2 else "None"
            for pos, col in enumerate(info["cols"], 1):
                c = col["name"]
                attr = attrs.get(c)
                if attr is None and t == "vehicle_position" and c == "position_ts":
                    attr = event_attrs["event_start_ts"]
                if attr is None and t == "vehicle_position" and c == "source_id":
                    # Rolled down from Event: a plain foreign key here, not part of an alternate key.
                    a = event_attrs["source_id"]
                    attr = (a[0], "FK", a[2], a[3], a[4])
                keys = []
                if c in info["pk"]:
                    keys.append("pk_" + t if len(info["pk"]) == 1 else f"pk_{t} ({len(info['pk'])} columns)")
                for akname, akcols in info["aks"].items():
                    if c in akcols:
                        keys.append(akname if len(akcols) == 1 else f"{akname} ({len(akcols)} columns)")
                comment = ccom.get(f"silver.{t}.{c}", "")
                rows.append({
                    "schema_name": "silver",
                    "table_name": t,
                    "entity_name": entity,
                    "subject_area": area,
                    "entity_kind": kind,
                    "supertype": spec["sup"],
                    "history": history,
                    "column_position": str(pos),
                    "column_name": c,
                    "attribute_name": attr[0] if attr else "",
                    "column_class": column_class(c, attr),
                    "domain": attr[2] if attr else "",
                    "data_type": col["type"],
                    "nullable": col["nullable"],
                    "default_or_generated": col["default"],
                    "logical_key": attr[1] if attr else "",
                    "physical_keys": "; ".join(keys),
                    "references": "; ".join(fks.get((t, c), [])),
                    "check_rule": "; ".join(info["checks"].get(c, [])),
                    "description": comment if comment else "(no comment in 07_comments.sql)",
                    "_table_comment": tcom.get(f"silver.{t}", ""),
                    "_definition": spec["defn"],
                })
    # Bronze register: not in the logical model, documented from script 06.
    for t, info in bronze.items():
        for pos, col in enumerate(info["cols"], 1):
            c = col["name"]
            keys = ["pk_" + t] if c in info["pk"] else []
            comment = ccom.get(f"bronze.{t}.{c}", "")
            rows.append({
                "schema_name": "bronze", "table_name": t, "entity_name": "", "subject_area": "Bronze",
                "entity_kind": "Register", "supertype": "", "history": "None",
                "column_position": str(pos), "column_name": c, "attribute_name": "",
                "column_class": "Audit" if c == "dw_loaded_ts" else "Register",
                "domain": "", "data_type": col["type"], "nullable": col["nullable"],
                "default_or_generated": col["default"], "logical_key": "",
                "physical_keys": "; ".join(keys),
                "references": col["inline"].get("ref", ""),
                "check_rule": "; ".join(info["checks"].get(c, [])),
                "description": comment if comment else "(no column comment in 06_bronze_register.sql)",
                "_table_comment": tcom.get(f"bronze.{t}", ""),
                "_definition": tcom.get(f"bronze.{t}", ""),
            })
    return rows


# ---------------------------------------------------------------- render
def render_csv(rows: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=CSV_COLUMNS, lineterminator="\n", extrasaction="ignore")
    w.writeheader()
    for r in rows:
        w.writerow(r)
    return buf.getvalue()


def md_cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def render_md(rows: list[dict]) -> str:
    tables: dict = {}
    for r in rows:
        tables.setdefault((r["schema_name"], r["table_name"]), []).append(r)
    silver = [k for k in tables if k[0] == "silver"]
    ncols = sum(len(tables[k]) for k in silver)
    nocomment = [r for r in rows if r["description"].startswith("(no ")]
    lines = [
        "# Data dictionary",
        "",
        "Step 11 of the data-design method. **Generated, do not edit by hand.** Regenerate with "
        "`python database/generator/build_data_dictionary.py` from the repository root; "
        "`--check` confirms these files match the model.",
        "",
        "Sources: `database/generator/logical_model_spec.py` (entities, attributes, domains) and "
        "`database/sql/02`, `03`, `04`, `06` and `07` (physical types, keys, references, history and "
        "the `COMMENT ON` text). The same rows, one per column, are in `data-dictionary.csv`.",
        "",
        "## Summary",
        "",
        "| Item | Count |",
        "| --- | --- |",
        f"| Silver tables | {len(silver)} |",
        f"| Silver columns | {ncols} |",
        f"| Silver tables with SCD Type 2 history | {len({k for k in silver if tables[k][0]['history'] == 'SCD Type 2'})} |",
        f"| Bronze tables | {len([k for k in tables if k[0] == 'bronze'])} |",
        f"| Columns with no comment in the database | {len(nocomment)} |",
        "",
        "## How to read it",
        "",
        "| Field | Meaning |",
        "| --- | --- |",
        "| Attribute | The logical attribute name in Logical Model V1. Empty for audit, history and derived columns |",
        "| Class | Logical (from the model), Audit (`dw_` columns), SCD2 (`valid_from_ts`), Derived (computed by the database), Register (bronze) |",
        "| Domain | The logical domain, which sets the type and the check rule |",
        "| Null | Yes if the column may be empty |",
        "| Keys | Physical primary key (`pk_`) and alternate keys (`ak1_`, `ak2_`) the column belongs to |",
        "| References | The column a foreign key points to |",
        "| Check | The CHECK constraint on the column |",
        "",
        "Times are `timestamptz`, stored in UTC and shown in Halifax time (America/Halifax). "
        "Geometry is `geometry(Geometry, 4326)` (WGS 84). See `standards.md` for the rules behind these choices.",
        "",
    ]
    if nocomment:
        lines += ["Columns with no comment in the database (a gap to close in `07_comments.sql` through the generator):", ""]
        for r in nocomment:
            lines.append(f"- `{r['schema_name']}.{r['table_name']}.{r['column_name']}`")
        lines.append("")

    lines += ["## Contents", ""]
    for area in AREA_ORDER + ["Bronze"]:
        names = [k[1] for k, v in tables.items() if v[0]["subject_area"] == area]
        lines.append(f"- **{area}:** " + ", ".join(f"`{n}`" for n in names))
    lines.append("")

    for area in AREA_ORDER + ["Bronze"]:
        lines += [f"## {area}", ""]
        for (schema, t), cols in tables.items():
            first = cols[0]
            if first["subject_area"] != area:
                continue
            title = f"{schema}.{t}"
            lines += [f"### {title}", ""]
            if first["entity_name"]:
                kind = first["entity_kind"] + (f" of {first['supertype']}" if first["supertype"] else "")
                lines.append(f"**{first['entity_name']}** ({kind}). {first['_definition']}")
            else:
                lines.append(first["_definition"])
            lines.append("")
            lines.append(f"History: {first['history']}.")
            lines.append("")
            lines += [
                "| # | Column | Attribute | Class | Domain | Type | Null | Keys | References | Check | Description |",
                "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
            ]
            for r in cols:
                typ = r["data_type"] + (f"; {r['default_or_generated']}" if r["default_or_generated"] else "")
                lines.append("| " + " | ".join(md_cell(x) for x in [
                    r["column_position"], f"`{r['column_name']}`", r["attribute_name"], r["column_class"],
                    r["domain"], typ, r["nullable"], r["physical_keys"], r["references"],
                    r["check_rule"], r["description"],
                ]) + " |")
            lines.append("")
    return "\n".join(lines)


def outputs() -> dict:
    rows = build_rows()
    return {
        "data-dictionary.csv": render_csv(rows),
        "data-dictionary.md": render_md(rows),
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare with the files on disk; exit 1 on any difference")
    ap.add_argument("--out-dir", default=OUT_DIR, help="where to write (default engineering/model)")
    args = ap.parse_args(argv)
    files = outputs()
    stale = []
    for name, text in files.items():
        path = os.path.join(args.out_dir, name)
        data = text.encode("utf-8")
        if args.check:
            try:
                with open(path, "rb") as fh:
                    if fh.read() != data:
                        stale.append(name)
            except FileNotFoundError:
                stale.append(name)
        else:
            os.makedirs(args.out_dir, exist_ok=True)
            with open(path, "wb") as fh:
                fh.write(data)
    if args.check:
        if stale:
            print("Out of date: " + ", ".join(stale) + ". Run build_data_dictionary.py.")
            return 1
        print("Data dictionary is up to date.")
        return 0
    print(f"Wrote {', '.join(files)} to {args.out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
